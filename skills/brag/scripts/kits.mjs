#!/usr/bin/env node
/**
 * Scene kits: brand-themed building blocks for common brag moments.
 *
 *   node <skill-root>/scripts/kits.mjs list
 *   node <skill-root>/scripts/kits.mjs install <composition-dir>
 *
 * `install` writes <composition-dir>/assets/brag-kits.js, a classic script that defines
 * window.BragKits. Load it after GSAP, give each kit an empty slot element, and mount kits in
 * the timeline script before registering the timeline:
 *
 *   <script src="assets/vendor/gsap.min.js"></script>
 *   <script src="assets/brag-kits.js"></script>
 *   ...
 *   <div id="install-slot"></div>
 *   ...
 *   const tl = gsap.timeline({ paused: true });
 *   BragKits.mount(tl, "install-slot", "terminal", { id: "install", at: 7.1, theme, props: { lines: [...] } });
 *   window.__timelines["main"] = tl;
 *
 * Kits and their props live in kits-core.mjs.
 */

import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { KITS } from "./kits-core.mjs";

export { KITS, renderKit, highlightCode, mountKit } from "./kits-core.mjs";

const CORE = fileURLToPath(new URL("./kits-core.mjs", import.meta.url));

/** kits-core.mjs as a classic browser script: works from file:// and inside Hyperframes renders. */
export function browserBundle(source = readFileSync(CORE, "utf8")) {
  const body = source.replace(/^export (const|function) /gm, "$1 ");
  if (/^\s*(import|export)\b/m.test(body)) throw new Error("kits-core.mjs must not import or re-export; the browser bundle cannot resolve modules.");
  return `/* brag scene kits — generated by kits.mjs install; do not edit */\n(function () {\n${body}\nwindow.BragKits = { KITS: KITS, render: renderKit, mount: mountKit, highlightCode: highlightCode };\n})();\n`;
}

export function installKits(compositionDir) {
  const target = path.join(compositionDir, "assets", "brag-kits.js");
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, browserBundle());
  return target;
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const [command, dir] = process.argv.slice(2);
  if (command === "list") {
    for (const [name, kit] of Object.entries(KITS)) console.log(`${name.padEnd(14)} ${kit.description}\n${" ".repeat(15)}example props: ${JSON.stringify(kit.example)}`);
  } else if (command === "install" && dir) {
    console.log(installKits(dir));
  } else {
    console.error("Usage: kits.mjs list | install <composition-dir>");
    process.exitCode = 2;
  }
}
